import puppeteer from "puppeteer-core";
const B = "https://resto.vylonium.biz.id";
const b = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args:["--no-sandbox","--disable-gpu"] });
const p = await b.newPage();
p.on("response", (r) => { if (r.url().includes("/api/") || r.status() >= 400) console.log("RES", r.status(), r.request().method(), r.url()); });
p.on("pageerror", (e) => console.log("PAGEERROR", String(e).slice(0,200)));
await p.goto(B + "/admin/", { waitUntil: "networkidle0" });
await p.type("#sandi", "xoxvj90i3999");
await p.click("button[type=submit]");
await p.waitForFunction(() => location.pathname === "/admin/", { timeout: 15000 });
await new Promise((r) => setTimeout(r, 1200));
await p.evaluate(() => [...document.querySelectorAll(".admin__tab")].find(e => e.textContent.trim() === "Teks situs").click());
await p.waitForSelector("#k-parkir", { timeout: 10000 });
await new Promise((r) => setTimeout(r, 800));
console.log("nilai awal:", await p.$eval("#k-parkir", (e) => e.value));
await p.evaluate(() => {
  const t = document.querySelector("#k-parkir");
  const setter = Object.getOwnPropertyDescriptor(window.HTMLTextAreaElement.prototype, "value").set;
  setter.call(t, "Parkir di belakang gedung, muat dua belas mobil. Uji panel.");
  t.dispatchEvent(new Event("input", { bubbles: true }));
});
await new Promise((r) => setTimeout(r, 400));
await p.evaluate(() => [...document.querySelectorAll("button")].find(e => e.textContent.trim().startsWith("Simpan perubahan")).click());
await new Promise((r) => setTimeout(r, 2500));
console.log("nilai setelah simpan:", await p.$eval("#k-parkir", (e) => e.value));
const r = await fetch(B + "/api/konten").then(r => r.json());
console.log("server parkir:", r.data.parkir);
await b.close();
